// Minimal Gmsh .geo reader for benchmark geometry previews.
// Supports the subset used by the benchmark meshes: numeric variables, Point, Line,
// Circle, Curve Loop, Plane Surface, Transfinite Curve/Surface, translation Extrude
// (with `out[] = Extrude ...` lists) and Physical Curve/Surface groups.
// Other statements (Recombine, Mesh options, ...) are ignored.
(() => {
  const FUNCTIONS = {
    Sqrt: Math.sqrt, Sin: Math.sin, Cos: Math.cos, Tan: Math.tan, Atan: Math.atan, Atan2: Math.atan2,
    Exp: Math.exp, Log: Math.log, Fabs: Math.abs, Abs: Math.abs, Floor: Math.floor, Ceil: Math.ceil, Round: Math.round,
  };

  function evaluate(expression, variables) {
    const tokens = expression.match(/\d*\.?\d+(?:[eE][+-]?\d+)?|[A-Za-z_]\w*|[-+*/^(),[\]]/g) || [];
    let index = 0;
    const peek = () => tokens[index];
    const next = () => tokens[index++];
    function primary() {
      const token = next();
      if (token === "(") { const value = sum(); next(); return value; }
      if (token === "-") return -power();
      if (token === "+") return power();
      if (/^[\d.]/.test(token ?? "")) return Number(token);
      if (token === "Pi") return Math.PI;
      if (token in FUNCTIONS) {
        next();
        const args = [sum()];
        while (peek() === ",") { next(); args.push(sum()); }
        next();
        return FUNCTIONS[token](...args);
      }
      if (token in variables && peek() === "[") {
        next();
        const item = variables[token][Math.round(sum())];
        next();
        if (item === undefined) throw new Error(`Index out of range in "${expression}"`);
        return item;
      }
      if (token in variables && !Array.isArray(variables[token])) return variables[token];
      throw new Error(`Unknown value ${token ?? "(end)"} in "${expression}"`);
    }
    function power() {
      const base = primary();
      if (peek() === "^") { next(); return base ** power(); }
      return base;
    }
    function product() {
      let value = power();
      while (peek() === "*" || peek() === "/") value = next() === "*" ? value * power() : value / power();
      return value;
    }
    function sum() {
      let value = product();
      while (peek() === "+" || peek() === "-") value = next() === "+" ? value + product() : value - product();
      return value;
    }
    const value = sum();
    if (index !== tokens.length || !Number.isFinite(value)) throw new Error(`Invalid expression "${expression}"`);
    return value;
  }

  const splitList = (text) => text.split(",").map((part) => part.trim()).filter(Boolean);

  // Split on top-level semicolons only, so `Extrude {...} { Surface{1}; Layers{1}; };` stays whole.
  function statements(text) {
    const result = [];
    let depth = 0;
    let quoted = false;
    let start = 0;
    for (let i = 0; i < text.length; i += 1) {
      const char = text[i];
      if (char === '"') quoted = !quoted;
      if (quoted) continue;
      if (char === "{") depth += 1;
      else if (char === "}") depth -= 1;
      else if (char === ";" && depth === 0) {
        result.push(text.slice(start, i));
        start = i + 1;
      }
    }
    result.push(text.slice(start));
    return result.map((statement) => statement.replace(/\s+/g, " ").trim()).filter(Boolean);
  }

  function parse(source) {
    const text = source.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");
    const variables = {};
    const model = {
      points: new Map(), curves: new Map(), loops: new Map(), surfaces: new Map(),
      // Entities generated by Extrude, keyed by synthetic ids handed out through `out[]` lists.
      extruded: new Map(), extrusion: null,
      physicalCurves: [], physicalSurfaces: [],
    };
    let nextGeneratedId = 1e6;
    const generate = (entity) => {
      nextGeneratedId += 1;
      model.extruded.set(nextGeneratedId, entity);
      return nextGeneratedId;
    };
    const numbers = (list) => splitList(list).map((item) => evaluate(item, variables));
    const ids = (list) => numbers(list).map(Math.round);

    for (const statement of statements(text)) {
      let match;
      if ((match = statement.match(/^(?:([A-Za-z_]\w*)\[\] = )?Extrude \{(.+?)\} \{(.*)\}$/))) {
        const [dx = 0, dy = 0, dz = 0] = numbers(match[2]);
        const out = [];
        let layers = 1;
        for (const item of match[3].split(";").map((part) => part.trim()).filter(Boolean)) {
          const entity = item.match(/^(Surface|Curve|Line|Layers)\s*\{(.+)\}$/);
          if (!entity) continue;
          if (entity[1] === "Layers") { layers = Math.round(numbers(entity[2])[0]); continue; }
          for (const id of ids(entity[2]).map(Math.abs)) {
            if (entity[1] === "Surface") {
              // Gmsh order: top surface, volume, then one lateral surface per boundary curve.
              out.push(generate({ kind: "cap", surface: id }), generate({ kind: "volume", surface: id }));
              const loop = model.loops.get(model.surfaces.get(id)?.loops[0]) || [];
              loop.forEach((curveId) => out.push(generate({ kind: "side", curve: Math.abs(curveId) })));
            } else {
              // Gmsh order: top curve, then the lateral surface.
              out.push(generate({ kind: "topCurve", curve: id }), generate({ kind: "side", curve: id }));
            }
          }
        }
        model.extrusion ??= { vector: { x: dx, y: dy, z: dz }, layers };
        if (match[1]) variables[match[1]] = out;
      } else if ((match = statement.match(/^([A-Za-z_]\w*) = (.+)$/))) {
        variables[match[1]] = evaluate(match[2], variables);
      } else if ((match = statement.match(/^Point\s*\((.+?)\) = \{(.+)\}$/))) {
        const [x = 0, y = 0, z = 0] = numbers(match[2]);
        model.points.set(Math.round(evaluate(match[1], variables)), { x, y, z });
      } else if ((match = statement.match(/^(Line|Circle)\s*\((.+?)\) = \{(.+)\}$/))) {
        const nodes = ids(match[3]);
        const curve = match[1] === "Line"
          ? { type: "line", start: nodes[0], end: nodes[1] }
          : { type: "circle", start: nodes[0], center: nodes[1], end: nodes[2] };
        model.curves.set(Math.round(evaluate(match[2], variables)), curve);
      } else if ((match = statement.match(/^Transfinite (?:Curve|Line) \{(.+?)\} = (.+?)(?: Using (Progression|Bump) (.+))?$/))) {
        const count = Math.round(evaluate(match[2], variables));
        const law = { type: (match[3] || "Progression").toLowerCase(), coefficient: match[4] ? evaluate(match[4], variables) : 1 };
        for (const id of ids(match[1])) {
          const curve = model.curves.get(Math.abs(id));
          if (curve) curve.transfinite = { count, ...law };
        }
      } else if ((match = statement.match(/^(?:Curve|Line) Loop\s*\((.+?)\) = \{(.+)\}$/))) {
        model.loops.set(Math.round(evaluate(match[1], variables)), ids(match[2]));
      } else if ((match = statement.match(/^Plane Surface\s*\((.+?)\) = \{(.+)\}$/))) {
        model.surfaces.set(Math.round(evaluate(match[1], variables)), { loops: ids(match[2]), transfinite: false });
      } else if ((match = statement.match(/^Transfinite Surface \{(.+?)\}/))) {
        for (const id of ids(match[1])) {
          const surface = model.surfaces.get(id);
          if (surface) surface.transfinite = true;
        }
      } else if ((match = statement.match(/^Physical (?:Curve|Line)\s*\(\s*"([^"]+)"[^)]*\) = \{(.+)\}$/))) {
        model.physicalCurves.push({ name: match[1], curves: ids(match[2]).map(Math.abs) });
      } else if ((match = statement.match(/^Physical Surface\s*\(\s*"([^"]+)"[^)]*\) = \{(.+)\}$/))) {
        model.physicalSurfaces.push({ name: match[1], surfaces: ids(match[2]).map(Math.abs) });
      }
    }
    return model;
  }

  function point(model, id) {
    const value = model.points.get(id);
    if (!value) throw new Error(`Point ${id} is not defined.`);
    return value;
  }

  // Position along a curve for t in [0, 1], following its definition direction.
  function curvePoint(model, curve, t) {
    const start = point(model, curve.start);
    const end = point(model, curve.end);
    if (curve.type === "line") {
      return { x: start.x + (end.x - start.x) * t, y: start.y + (end.y - start.y) * t };
    }
    const center = point(model, curve.center);
    const radius = Math.hypot(start.x - center.x, start.y - center.y);
    const a0 = Math.atan2(start.y - center.y, start.x - center.x);
    let sweep = Math.atan2(end.y - center.y, end.x - center.x) - a0;
    // Gmsh circle arcs are always the short way round (strictly below pi).
    if (sweep > Math.PI) sweep -= 2 * Math.PI;
    if (sweep < -Math.PI) sweep += 2 * Math.PI;
    const angle = a0 + sweep * t;
    return { x: center.x + radius * Math.cos(angle), y: center.y + radius * Math.sin(angle) };
  }

  function samplePolyline(model, curve) {
    const segments = curve.type === "circle" ? 32 : 1;
    return Array.from({ length: segments + 1 }, (_, index) => curvePoint(model, curve, index / segments));
  }

  // Normalised node parameters for a transfinite curve.
  function nodeParameters({ count, type, coefficient }) {
    const intervals = Math.max(1, count - 1);
    const sizes = Array.from({ length: intervals }, (_, k) => {
      if (type === "bump") {
        // Approximation of Gmsh's bump law: end/middle size ratio equals the coefficient.
        const c = (coefficient - 1) / (coefficient + 1);
        return 1 - c * Math.cos(2 * Math.PI * (k + 0.5) / intervals);
      }
      return coefficient ** k;
    });
    const total = sizes.reduce((a, b) => a + b, 0);
    let position = 0;
    return [0, ...sizes.map((size) => (position += size) / total)];
  }

  function orientedNodes(model, signedId) {
    const curve = model.curves.get(Math.abs(signedId));
    if (!curve?.transfinite) return null;
    const nodes = nodeParameters(curve.transfinite).map((t) => curvePoint(model, curve, t));
    return signedId < 0 ? nodes.reverse() : nodes;
  }

  // Structured quad grid for a 4-sided transfinite surface (Coons patch).
  function transfiniteGrid(model, surface) {
    const loop = model.loops.get(surface.loops[0]);
    if (!surface.transfinite || surface.loops.length !== 1 || loop?.length !== 4) return null;
    const sides = loop.map((id) => orientedNodes(model, id));
    if (sides.some((side) => !side)) return null;
    const [bottom, right, topReversed, leftReversed] = sides;
    const top = [...topReversed].reverse();
    const left = [...leftReversed].reverse();
    if (bottom.length !== top.length || left.length !== right.length) return null;
    const nu = bottom.length;
    const nv = left.length;
    const c00 = bottom[0], c10 = bottom[nu - 1], c01 = top[0], c11 = top[nu - 1];
    const nodes = [];
    for (let j = 0; j < nv; j += 1) {
      const v = j / (nv - 1);
      const row = [];
      for (let i = 0; i < nu; i += 1) {
        const u = i / (nu - 1);
        const blend = (key) => (1 - v) * bottom[i][key] + v * top[i][key] + (1 - u) * left[j][key] + u * right[j][key]
          - ((1 - u) * (1 - v) * c00[key] + u * (1 - v) * c10[key] + (1 - u) * v * c01[key] + u * v * c11[key]);
        row.push({ x: blend("x"), y: blend("y") });
      }
      nodes.push(row);
    }
    return { nu, nv, nodes };
  }

  function describe(model) {
    const surfaceCurves = new Set();
    model.surfaces.forEach((surface) => surface.loops.forEach((loopId) => {
      (model.loops.get(loopId) || []).forEach((id) => surfaceCurves.add(Math.abs(id)));
    }));
    const curves = [...model.curves.entries()].map(([id, curve]) => ({
      id,
      type: curve.type,
      boundary: surfaceCurves.has(id),
      group: model.physicalCurves.find((group) => group.curves.includes(id))?.name || null,
      polyline: samplePolyline(model, curve),
    }));

    const curveEnds = new Set([...model.curves.values()].flatMap((curve) => [curve.start, curve.end]));
    const xs = [...model.points.values()].map((p) => p.x);
    const ys = [...model.points.values()].map((p) => p.y);
    const bounds = { minX: Math.min(...xs), maxX: Math.max(...xs), minY: Math.min(...ys), maxY: Math.max(...ys) };
    bounds.width = bounds.maxX - bounds.minX;
    bounds.height = bounds.maxY - bounds.minY;

    // Group circle arcs by centre so each round obstacle reports one diameter.
    const circles = new Map();
    model.curves.forEach((curve) => {
      if (curve.type !== "circle") return;
      const center = point(model, curve.center);
      const start = point(model, curve.start);
      circles.set(curve.center, { x: center.x, y: center.y, radius: Math.hypot(start.x - center.x, start.y - center.y) });
    });

    const outline = (surface) => (model.loops.get(surface.loops[0]) || []).flatMap((signedId, index) => {
      const polyline = samplePolyline(model, model.curves.get(Math.abs(signedId)));
      const ordered = signedId < 0 ? polyline.reverse() : polyline;
      return index === 0 ? ordered : ordered.slice(1);
    });
    const outerLoops = [...model.surfaces.values()].map(outline);

    // Named surfaces resolved to drawable faces: planar faces (offset 0 or the extrusion
    // vector) and lateral faces swept from a curve along the extrusion vector.
    const zero = { x: 0, y: 0, z: 0 };
    const vector = model.extrusion?.vector || zero;
    const groups = model.physicalSurfaces.map(({ name, surfaces }) => ({
      name,
      faces: surfaces.flatMap((id) => {
        if (model.surfaces.has(id)) return [{ type: "plane", loop: outline(model.surfaces.get(id)), offset: zero }];
        const entity = model.extruded.get(id);
        if (entity?.kind === "cap") return [{ type: "plane", loop: outline(model.surfaces.get(entity.surface)), offset: vector }];
        if (entity?.kind === "side") return [{ type: "side", curve: entity.curve, polyline: samplePolyline(model, model.curves.get(entity.curve)), vector }];
        return [];
      }),
    })).filter((group) => group.faces.length);
    // Colour curves by the named surface swept from them (or by their own physical curve group).
    const curveGroup = new Map();
    groups.forEach((group) => group.faces.forEach((face) => { if (face.type === "side") curveGroup.set(face.curve, group.name); }));
    curves.forEach((curve) => { curve.group = curveGroup.get(curve.id) || curve.group; });

    return {
      curves,
      bounds,
      circles: [...circles.values()],
      surfaces: outerLoops,
      points: [...model.points.entries()].map(([id, p]) => ({ id, ...p, onCurve: curveEnds.has(id) })),
      groups,
      extrusion: model.extrusion,
      grids: () => [...model.surfaces.values()].map((surface) => transfiniteGrid(model, surface)).filter(Boolean),
    };
  }

  const cache = new Map();
  function load(path) {
    const url = window.FluidBenchPaths.url(path);
    if (!cache.has(url)) {
      cache.set(url, fetch(url).then((response) => {
        if (!response.ok) throw new Error(`Could not load ${url} (${response.status}).`);
        return response.text();
      }).then((source) => describe(parse(source))));
    }
    return cache.get(url);
  }

  const formatLength = (value) => Number(value.toFixed(3)).toString();

  window.FluidBenchGeo = { parse, describe, load, formatLength };
})();
